  await page.screenshot({ path: "../.tmp/library-cards.png" });
  await library.getByRole("button", { name: "Close Library" }).click();
  await tray.hover();
  await expect(tray.getByRole("button", { name: "Place Task Board", exact: true })).toBeEnabled();
