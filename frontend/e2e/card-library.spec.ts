  await expect(tray.getByRole("tab", { name: /Quick tools/ }).locator("svg")).toHaveClass(/lucide-zap/);
  await expect(tray.getByRole("tab", { name: /Research kit/ }).locator("svg")).toHaveClass(/lucide-folder/);
