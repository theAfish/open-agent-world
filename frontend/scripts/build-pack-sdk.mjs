import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { access, readFile, readdir, realpath, rm, writeFile } from 'node:fs/promises';
import { buildRuntime, cachedBuild, digest, filesFingerprint, treeFingerprint } from './build-cache.mjs';
import { checkProject, dependencyFingerprint } from './source-packs.mjs';

const defaultRoot = fileURLToPath(new URL('../', import.meta.url));
export async function buildPackSdk({ root = defaultRoot, force = false } = {}) {
  root = path.resolve(root);
  const started = performance.now();
  const sdkRoot = await realpath(path.join(root, 'pack-sdk'));
  if (path.dirname(sdkRoot) !== await realpath(root)) throw new Error('SDK output must stay inside frontend');
  const typesDirectory = path.join(sdkRoot, 'types');
  const exportsFile = path.join(sdkRoot, 'sdk-exports.mjs');
  const built = await cachedBuild({
    receiptFile: path.join(root, 'node_modules/.cache/oaw/pack-sdk.json'), force,
    inputs: async () => digest(JSON.stringify([
      buildRuntime(), await treeFingerprint(path.join(root, 'src')),
      await dependencyFingerprint(root),
      await filesFingerprint([
        ...['build-pack-sdk.mjs', 'build-cache.mjs', 'source-packs.mjs', 'pack-sdk-exports.mjs'].map(file => path.join(root, 'scripts', file)),
        ...(await readdir(root)).filter(file => /^tsconfig.*\.json$/.test(file)).map(file => path.join(root, file)),
      ]),
    ])),
    outputs: async () => digest(JSON.stringify([
      await treeFingerprint(typesDirectory), await filesFingerprint([exportsFile]),
    ])),
    build: async () => {
      await checkProject(root);
      const { default: ts } = await import('typescript');
      const { sdkRuntimeExports } = await import('./pack-sdk-exports.mjs');
      const config = ts.readConfigFile(path.join(root, 'tsconfig.app.json'), ts.sys.readFile);
      const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
      const program = ts.createProgram([path.join(root, 'src/plugins/sdk.ts'), path.join(root, 'src/vite-env.d.ts')], {
        ...parsed.options, noEmit: false, declaration: true, emitDeclarationOnly: true,
        rootDir: path.join(root, 'src'), outDir: typesDirectory,
      });
      const diagnostics = [config.error, ...parsed.errors, ...ts.getPreEmitDiagnostics(program)].filter(Boolean);
      const report = errors => ts.formatDiagnosticsWithColorAndContext(errors, {
        getCanonicalFileName: f => f, getCurrentDirectory: () => root, getNewLine: () => '\n',
      });
      const errors = diagnostics.filter(d => d.category === ts.DiagnosticCategory.Error);
      if (errors.length) throw new Error(report(errors));
      // Do not discard working declarations before source validation succeeds.
      await rm(typesDirectory, { recursive: true, force: true });
      const result = program.emit();
      const emitErrors = result.diagnostics.filter(d => d.category === ts.DiagnosticCategory.Error);
      if (emitErrors.length) throw new Error(report(emitErrors));
      // TypeScript can set emitSkipped for non-emitting inputs such as JSON,
      // while successfully emitting the public declarations.
      await access(path.join(typesDirectory, 'plugins/sdk.d.ts'));
      const exports = '// Generated by npm run build:pack-sdk from src/plugins/sdk.ts. Do not edit.\n'
        + `export default ${JSON.stringify(sdkRuntimeExports(program, path.join(root, 'src/plugins/sdk.ts')))};\n`;
      if (await readFile(exportsFile, 'utf8').catch(() => null) !== exports) await writeFile(exportsFile, exports);
    },
  });
  console.log(`[Pack SDK] ${built ? 'Built' : 'Reused'} (${((performance.now() - started) / 1000).toFixed(2)}s)`);
  return built;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildPackSdk({ force: process.argv.includes('--force') });
}
